/// Prueft, ob ein Codepoint Buchstabe oder Ziffer ist.
pub fn isAlphanumeric(codepoint: u21) bool {
    if (codepoint < 0x80) {
        return std.ascii.isAlphanumeric(@intCast(codepoint));
    }
    return inRanges(&alnum_ranges, codepoint);
}

/// Prueft, ob ein Codepoint ein Grossbuchstabe ist.
pub fn isUpperCase(codepoint: u21) bool {
    if (codepoint < 0x80) {
        return std.ascii.isUpper(@intCast(codepoint));
    }
    return inRanges(&upper_ranges, codepoint);
}

/// Prueft, ob ein Codepoint eine Ziffer ist.
pub fn isDigit(codepoint: u21) bool {
    if (codepoint < 0x80) {
        return codepoint >= '0' and codepoint <= '9';
    }
    return inRanges(&digit_ranges, codepoint);
}

/// Liefert die Grossschreibung eines Codepoints.
///
/// Null bedeutet: der Codepoint bleibt unveraendert.
pub fn upperMapping(codepoint: u21) ?[]const u8 {
    var low: usize = 0;
    var high: usize = upper_mappings.len;
    while (low < high) {
        const middle = low + (high - low) / 2;
        const entry = upper_mappings[middle];
        if (codepoint < entry.codepoint) {
            high = middle;
        } else if (codepoint > entry.codepoint) {
            low = middle + 1;
        } else {
            return entry.mapped;
        }
    }
    return null;
}

fn inRanges(table: []const Range, codepoint: u21) bool {
    var low: usize = 0;
    var high: usize = table.len;
    while (low < high) {
        const middle = low + (high - low) / 2;
        const entry = table[middle];
        if (codepoint < entry.start) {
            high = middle;
        } else if (codepoint > entry.end) {
            low = middle + 1;
        } else {
            return true;
        }
    }
    return false;
}

test "Alphanumerisch folgt den Kategorien L und N" {
    try std.testing.expect(isAlphanumeric('a'));
    try std.testing.expect(isAlphanumeric('7'));
    try std.testing.expect(isAlphanumeric(0x00E9)); // e mit Akzent, Ll
    try std.testing.expect(isAlphanumeric(0x4E00)); // CJK, Lo
    try std.testing.expect(isAlphanumeric(0x2160)); // Römische Ziffer, Nl
    try std.testing.expect(!isAlphanumeric(' '));
    try std.testing.expect(!isAlphanumeric(0x2019)); // typografisches Apostroph, Pf
}

test "Grossbuchstaben folgen Lu und Other_Uppercase" {
    try std.testing.expect(isUpperCase('A'));
    try std.testing.expect(isUpperCase(0x00C4)); // Ä, Lu
    try std.testing.expect(isUpperCase(0x2160)); // Römische Ziffer, Other_Uppercase
    try std.testing.expect(isUpperCase(0x24B6)); // eingekreister Buchstabe, Other_Uppercase
    try std.testing.expect(!isUpperCase('a'));
    try std.testing.expect(!isUpperCase(0x01C5)); // Dž, Lt
}

test "Ziffern folgen Nd und Numeric_Type Digit" {
    try std.testing.expect(isDigit('0'));
    try std.testing.expect(isDigit(0x0660)); // Arabic-Indic Digit Zero, Nd
    try std.testing.expect(isDigit(0x00B2)); // Quadrat zwei, Numeric_Type Digit
    try std.testing.expect(isDigit(0x2460)); // eingekreiste Eins, Numeric_Type Digit
    try std.testing.expect(!isDigit(0x2167)); // Römische Ziffer, Nl
    try std.testing.expect(!isDigit('a'));
}

test "Grossschreibung nutzt einfache und unbedingte Zuordnung" {
    try std.testing.expectEqualStrings("\u{00C4}", upperMapping(0x00E4).?);
    try std.testing.expectEqualStrings("SS", upperMapping(0x00DF).?);
    try std.testing.expectEqualStrings("\u{01C4}", upperMapping(0x01C5).?);
    try std.testing.expectEqualStrings("FFI", upperMapping(0xFB03).?);
    try std.testing.expectEqualStrings("A", upperMapping('a').?);
    try std.testing.expect(upperMapping('A') == null);
}
